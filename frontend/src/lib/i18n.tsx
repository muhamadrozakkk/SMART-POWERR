export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("ID");
  useEffect(() => { const timer = window.setTimeout(() => { const saved = window.localStorage.getItem("spw_locale"); if (saved === "EN" || saved === "ID") setLocaleState(saved); }, 0); return () => window.clearTimeout(timer); }, []);
  useEffect(() => { document.documentElement.lang = locale === "EN" ? "en" : "id"; }, [locale]);
  const setLocale = (next: Locale) => { setLocaleState(next); window.localStorage.setItem("spw_locale", next); window.dispatchEvent(new CustomEvent("spw:locale-updated", { detail: next })); };
  const value = useMemo<I18nValue>(() => ({ locale, setLocale, t: (text) => locale === "EN" ? en[text] ?? text : text }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used within I18nProvider");
  return value;
}
